"""One table over every IW game built: reports/iw/README.md (the per-game reports beside it).

    py -3.11 -I summary.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build  # noqa: E402

GAMES = ["iw1", "iw3", "iw4", "iw5", "iw6", "s1", "h1", "iw7", "iw8", "jup", "jup_sp"]


def main():
    rows = []
    for g in GAMES:
        if not os.path.exists(os.path.join(HERE, "out", g + ".json")):
            rows.append((g, "not extracted", "", "", "", "", ""))
            continue
        doc = build.load(g)
        ents, fn, me = build.entries(doc, g)
        ents, sp = build.merge_sp(g, doc, ents)
        val = build.validate(g, ents, fn, me)
        n = len(ents)
        ar = sum(1 for e in ents if "min" in e)
        withp = [e for e in ents if "min" in e and e["max"] > 0]
        typed = sum(1 for e in withp if any(p != "?" for p in e["param_types"]))
        st = val["stats"] if val else {}
        exe = os.path.basename(doc["exe"]) + (" + " + os.path.basename(sp["exe"]) if sp else "")
        rows.append((g, exe, "%d (%d f, %d m)" % (n, sum(1 for e in ents if e["kind"] == "function"),
                                                 sum(1 for e in ents if e["kind"] == "method")),
                     "%.1f%%" % (100.0 * ar / max(n, 1)),
                     "%.1f%% of %d" % (100.0 * st.get("within", 0) / max(st.get("checked_sites", 0), 1),
                                       st.get("checked_sites", 0)) if val else "-",
                     "%d/%d" % (val["names_found"], val["names_called"]) if val else "-",
                     "%.1f%%" % (100.0 * typed / max(len(withp), 1))))
    L = ["# IW-engine builtin catalogues: summary", "",
         "Generated by `summary.py`. Per game: `<game>.md`. Data: `gruff-data/builtins/<game>.toml`.",
         "", "| game | executable(s) | entries | arity measured | corpus call sites within min..max "
         "| called names found | params typed |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append("| " + " | ".join(r) + " |")
    p = os.path.join(build.REPORTS, "README.md")
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
